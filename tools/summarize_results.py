"""Turn docs/results/*.json into the Markdown tables used in the README and
docs/LINK.md (thresholds are read off the simulated curves by log-linear
interpolation between neighbouring Monte Carlo points).

    python tools/summarize_results.py
"""

from __future__ import annotations

import json
import math
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
sys.path.insert(0, ROOT)

from sdrmesh import theory  # noqa: E402
from sdrmesh.link import budget_row  # noqa: E402
from sdrmesh.lora.params import LoRaParams  # noqa: E402


def load(name):
    with open(os.path.join(ROOT, "docs", "results", name + ".json"), encoding="utf-8") as f:
        return json.load(f)


def crossing(xs, ys, target):
    """x where y first falls below target (log-linear interpolation), or None."""
    pts = sorted(zip(xs, ys))
    for (x0, y0), (x1, y1) in zip(pts, pts[1:]):
        if y0 >= target > y1:
            if y1 <= 0:
                return x1
            l0, l1, lt = math.log10(max(y0, 1e-12)), math.log10(y1), math.log10(target)
            return x0 + (x1 - x0) * (l0 - lt) / (l0 - l1)
    return None


def main():
    out = []
    ble = load("ble_ber")
    out.append("### BLE: Eb/N0 needed for BER 1e-3 (simulated)\n")
    out.append("| channel | Eb/N0 @ BER 1e-3 | non-coherent BFSK theory | coherent MSK bound |")
    out.append("|---|---|---|---|")
    import numpy as np
    grid = np.arange(0, 20, 0.01)
    th_nc = crossing(grid, theory.ber_bfsk_noncoherent(grid), 1e-3)
    th_c = crossing(grid, theory.ber_msk_coherent(grid), 1e-3)
    for imp, fs in (("awgn", 4e6), ("cfo+sto", 4e6), ("multipath", 4e6), ("awgn", 2e6)):
        rows = [r for r in ble["results"] if r["impairment"] == imp and r.get("fs", 4e6) == fs]
        x = crossing([r["ebn0_db"] for r in rows], [r["ber"] for r in rows], 1e-3)
        name = f"{imp}, {fs / 1e6:g} MS/s"
        out.append(f"| {name} | {x:.1f} dB | {th_nc:.1f} dB | {th_c:.1f} dB |" if x else f"| {name} | n/a | | |")
    per = load("ble_per")
    x = crossing([r["ebn0_db"] for r in per["results"]], [r["per"] for r in per["results"]], 0.1)
    out.append(f"\nmeshfind advert PER 10 % (CRC + key recovered, random CFO/timing): **{x:.1f} dB Eb/N0** "
               f"({per['results'][0]['packets']} packets per point).\n")

    lser, lper = load("lora_ser"), load("lora_per")
    out.append("### LoRa: SNR thresholds (125 kHz, simulated vs theory)\n")
    out.append("| SF | uncoded SER 1e-3, sim | theory | PER 10 %, CR 4/5 | PER 10 %, CR 4/8 |")
    out.append("|---|---|---|---|---|")
    thr = {}
    for sf in range(7, 13):
        rows = [r for r in lser["results"] if r["sf"] == sf]
        xs = crossing([r["snr_db"] for r in rows], [r["ser"] for r in rows], 1e-3)
        g = np.arange(-35, 0, 0.02)
        xt = crossing(g, theory.lora_ser(sf, g), 1e-3)
        cells = []
        for cr in (1, 4):
            rr = [r for r in lper["results"] if r["sf"] == sf and r["cr"] == cr]
            xp = crossing([r["snr_db"] for r in rr], [r["per"] for r in rr], 0.1)
            thr[(sf, cr)] = xp
            cells.append(f"{xp:.1f} dB" if xp is not None else "n/a")
        out.append(f"| {sf} | {xs:.1f} dB | {xt:.1f} dB | {cells[0]} | {cells[1]} |")

    link = ["| SF | BW | CR | LoRa payload | time on air | reports / h at 1 % duty | goodput | sim. SNR @ PER 10 % "
            "| sensitivity (NF 6 dB) | max path loss at +14 dBm |", "|---|---|---|---|---|---|---|---|---|---|"]
    for sf in range(7, 13):
        for cr in (1, 4):
            r = budget_row(LoRaParams(sf=sf, bw=125e3, cr=cr), 2, snr_req_db=thr[(sf, cr)])
            link.append(f"| {sf} | 125 kHz | {r['cr']} | {r['payload_B']} B | {r['airtime_ms']:.0f} ms | "
                        f"{r['reports_per_hour']:.0f} | {r['goodput_bps']:.0f} bit/s | {r['snr_req_db']:.1f} dB | "
                        f"{r['sensitivity_dbm']:.1f} dBm | {r['max_path_loss_db']:.1f} dB |")
    text = "\n".join(out) + "\n"
    with open(os.path.join(ROOT, "docs", "results", "SUMMARY.md"), "w", encoding="utf-8") as f:
        f.write("# Monte Carlo summary\n\nGenerated by `tools/summarize_results.py` from the JSON files in this "
                f"directory ({ble['meta']['generated']}, {ble['meta']['machine']}). All values are simulated.\n\n")
        f.write(text)
        f.write("\n### meshfind over LoRa: two 120-byte report frames per packet\n\n" + "\n".join(link) + "\n")
    print(text)
    print("\n".join(link))


if __name__ == "__main__":
    main()
